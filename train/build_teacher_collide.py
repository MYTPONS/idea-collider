def load(name: str) -> dict[str, str]:
    path = ROOT / "data" / "domains" / name
    return {
        row["id"]: row["text"]
        for row in (json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip())
    }


def main() -> int:
    memory = load("memory_products.jsonl")
    rights = load("data_rights.jsonl")
    access = {f"c{key[1:]}": text for key, text in load("ai_access.jsonl").items()}
    pools = {"a": memory, "b": rights, "c": access}
    rows = []
    for key, forms in FORMS.items():
        near_id, far_id = key.split("x")
        near_text = pools[near_id[0]][near_id]
        far_text = pools[far_id[0]][far_id]
        for form in forms:
            rows.append(
                {
                    "task": "collide",
                    "input": {"near": near_text, "far": far_text},
                    "output": {
                        "interaction": True,
                        "must": f"{near_text[:18]}；同时{far_text[:18]}",
                        "form": f"{NAMES[key]}｜{form}",
                        "why": "两边约束同时成立,取舍已写进形态",
                    },
                    "source": "teacher-agent",
                }
            )
    out = ROOT / "data" / "collide_train2.jsonl"
    out.write_text("\n".join(json.dumps(r, ensure_ascii=False) for r in rows) + "\n", encoding="utf-8")
    print(f"{out} {len(rows)} 条")
    return 0


