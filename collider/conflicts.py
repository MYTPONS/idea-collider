# 能同时满足的组合:交集非空,应当砍掉,而不是当成候选。
COMPATIBLE_NOTE = "两边可以同时满足:已有形态就能覆盖,不构成碰撞"


def conflict_for(near_style: str, far_type: str) -> str | None:
    return CONFLICTS.get((near_style, far_type))
